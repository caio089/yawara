CREATE TABLE IF NOT EXISTS brand_ambassador (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  club TEXT,
  role TEXT NOT NULL DEFAULT 'Embaixadora',
  description TEXT,
  highlight TEXT,
  image TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS brand_ambassador_updated_at ON brand_ambassador;
CREATE TRIGGER brand_ambassador_updated_at
  BEFORE UPDATE ON brand_ambassador
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at();

ALTER TABLE brand_ambassador ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Embaixadora visível publicamente" ON brand_ambassador;
CREATE POLICY "Embaixadora visível publicamente"
  ON brand_ambassador FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin pode inserir embaixadora" ON brand_ambassador;
CREATE POLICY "Admin pode inserir embaixadora"
  ON brand_ambassador FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode atualizar embaixadora" ON brand_ambassador;
CREATE POLICY "Admin pode atualizar embaixadora"
  ON brand_ambassador FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode deletar embaixadora" ON brand_ambassador;
CREATE POLICY "Admin pode deletar embaixadora"
  ON brand_ambassador FOR DELETE TO authenticated USING (true);

