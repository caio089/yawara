CREATE TABLE IF NOT EXISTS sponsored_athletes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  club TEXT,
  image TEXT,
  display_row SMALLINT NOT NULL DEFAULT 1 CHECK (display_row IN (1, 2)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  image_position TEXT NOT NULL DEFAULT 'top' CHECK (image_position IN ('top', 'center')),
  role TEXT NOT NULL DEFAULT 'Patrocinado' CHECK (role IN ('Patrocinado', 'Patrocinada')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_sponsored_athletes_row_order
  ON sponsored_athletes (display_row, sort_order);

DROP TRIGGER IF EXISTS sponsored_athletes_updated_at ON sponsored_athletes;
CREATE TRIGGER sponsored_athletes_updated_at
  BEFORE UPDATE ON sponsored_athletes
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at();

ALTER TABLE sponsored_athletes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Patrocinados visíveis publicamente" ON sponsored_athletes;
CREATE POLICY "Patrocinados visíveis publicamente"
  ON sponsored_athletes FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin pode inserir patrocinados" ON sponsored_athletes;
CREATE POLICY "Admin pode inserir patrocinados"
  ON sponsored_athletes FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode atualizar patrocinados" ON sponsored_athletes;
CREATE POLICY "Admin pode atualizar patrocinados"
  ON sponsored_athletes FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode deletar patrocinados" ON sponsored_athletes;
CREATE POLICY "Admin pode deletar patrocinados"
  ON sponsored_athletes FOR DELETE TO authenticated USING (true);

