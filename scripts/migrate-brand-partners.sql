CREATE TABLE IF NOT EXISTS brand_partners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  club TEXT,
  image TEXT,
  role TEXT NOT NULL DEFAULT 'Parceiro' CHECK (role IN ('Parceiro', 'Amigo da Marca')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  image_position TEXT NOT NULL DEFAULT 'top' CHECK (image_position IN ('top', 'center')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_brand_partners_sort_order
  ON brand_partners (sort_order, id);

DROP TRIGGER IF EXISTS brand_partners_updated_at ON brand_partners;
CREATE TRIGGER brand_partners_updated_at
  BEFORE UPDATE ON brand_partners
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at();

ALTER TABLE brand_partners ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Parceiros visíveis publicamente" ON brand_partners;
CREATE POLICY "Parceiros visíveis publicamente"
  ON brand_partners FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin pode inserir parceiros" ON brand_partners;
CREATE POLICY "Admin pode inserir parceiros"
  ON brand_partners FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode atualizar parceiros" ON brand_partners;
CREATE POLICY "Admin pode atualizar parceiros"
  ON brand_partners FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Admin pode deletar parceiros" ON brand_partners;
CREATE POLICY "Admin pode deletar parceiros"
  ON brand_partners FOR DELETE TO authenticated USING (true);

